import { createServer } from 'vite';
import { chromium, devices } from '@playwright/test';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..', '..');
const server = await createServer({ configFile: resolve(root, 'vite.config.ts'), root, server: { port: 0, host: '127.0.0.1', hmr: false }, logLevel: 'error' });
await server.listen();
const port = server.httpServer.address().port;
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['Pixel 7'] });
const page = await ctx.newPage();
await page.goto(`http://127.0.0.1:${port}/?case=c00`);
await page.waitForFunction(() => window.__haystackReady === true, null, { timeout: 60000 });
const dump = async (label) => {
  console.log('=====', label);
  console.log(await page.evaluate(() => document.getElementById('app').innerText));
  console.log('--- buttons', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('button')].map(b => [b.innerText.trim(), b.getAttribute('aria-label'), b.getBoundingClientRect().y|0, getComputedStyle(b).visibility]))));
};
await dump('brief');
await page.touchscreen.tap(206, 700);  // hits start? check
await page.waitForTimeout(1500);
await dump('after tap 206,700');
await page.getByText('Commencer l’enquête').tap().catch(()=>{});
await page.waitForTimeout(2500);
await dump('play');
console.log(await page.evaluate(() => document.getElementById('app').innerHTML.slice(0, 5000)));
await page.screenshot({ path: '.shots/playtest-probe2.png', scale: 'css' });
await page.touchscreen.tap(206, 300);
await page.waitForTimeout(1500);
await dump('after tap map');
await page.screenshot({ path: '.shots/playtest-probe3.png', scale: 'css' });
await page.touchscreen.tap(206, 300);
await page.waitForTimeout(1500);
await dump('after tap map 2');
await page.screenshot({ path: '.shots/playtest-probe4.png', scale: 'css' });
console.log(await page.evaluate(() => document.getElementById('app').innerHTML.slice(0, 7000)));
await browser.close(); await server.close();
